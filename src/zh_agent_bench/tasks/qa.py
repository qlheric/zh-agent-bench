QA_FILENAME = "qa.jsonl"


def _dump_line(task: Task) -> str:
    return json.dumps(task.to_dict(), ensure_ascii=False, separators=(",", ":")) + "\n"


def write_qa_dataset(tasks: Sequence[Task], output_dir: Path) -> Path:
    """写成单文件 ``<output_dir>/qa.jsonl``。原子写（临时文件 + ``os.replace``）。

    单文件而非 train/heldout 分目录：B 场景试标阶段规模小，且 judge 校准要**整批一起看**，
    按 split 拆开反而不好使。A 场景的分目录是那份锁定的判据要求的，这里不照抄。
    """
    output_dir.mkdir(parents=True, exist_ok=True)
    target = output_dir / QA_FILENAME
    payload = "".join(_dump_line(t) for t in sorted(tasks, key=lambda t: t.id))
    tmp = target.with_suffix(target.suffix + ".tmp")
    tmp.write_text(payload, encoding="utf-8", newline="\n")
    os.replace(tmp, target)
    return target


def _validate_args(per_type: int, seed: int) -> None:
    """边界校验必须发生在任何写盘动作之前 —— 非法输入不该留半份产物。"""
    if per_type < 1:
        raise ValueError(f"--per-type 必须 >= 1，收到 {per_type}")
    if not isinstance(seed, int) or isinstance(seed, bool):
        raise ValueError(f"--seed 必须为整数，收到 {seed!r}")


def _formal_summary(tasks: Sequence[FormalTask], seed: int, output_dir: Path) -> None:
    """正式集的 stdout 汇总表。表头用 ASCII（同 :func:`main` 的理由：控制台代码页）。"""
    print(f"preset=formal seed={seed} output={output_dir}")
    print(f"{'split':<10}{'type':<14}{'total':>8}{'points':>9}{'bases':>8}")
    for split in B_SPLITS:
        rows = [ft for ft in tasks if ft.split == split]
        for task_type in TASK_TYPES:
            sub = [ft for ft in rows if ft.task_type == task_type]
            if not sub:
                continue
            bases = len({ft.base_id for ft in sub})
            pts = sum(len(ft.task.rubric or ()) for ft in sub)
            print(f"{split:<10}{TYPE_LABELS[task_type]:<14}{len(sub):>8}{pts:>9}{bases:>8}")
        pts = sum(len(ft.task.rubric or ()) for ft in rows)
        print(f"{split:<10}{'SUBTOTAL':<14}{len(rows):>8}{pts:>9}"
              f"{len({ft.base_id for ft in rows}):>8}")
    print(f"{'TOTAL':<10}{'':14}{len(tasks):>8}"
          f"{sum(len(ft.task.rubric or ()) for ft in tasks):>9}"
          f"{len({ft.base_id for ft in tasks}):>8}")


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="python -m zh_agent_bench.tasks.qa",
        description="生成 zh-agent-bench 的 B 场景任务（知识检索 QA，带 rubric）",
    )
    parser.add_argument("--seed", type=int, default=42, help="随机种子，决定每类挑哪几个场景")
    parser.add_argument("--per-type", type=int, default=2, help="每个任务类型生成多少条（>=1）")
    parser.add_argument(
        "--preset", choices=("trial", "formal"), default="trial",
        help="trial=按场景池抽 N 条（试标/校准用）；formal=330 条三 split（正式校准用）",
    )
    parser.add_argument(
        "--output-dir", type=Path, default=Path("benchmarks/qa"), help="输出目录（写 qa.jsonl）"
    )
    args = parser.parse_args(argv)

    if not isinstance(args.seed, int) or isinstance(args.seed, bool):
        parser.error(f"--seed 必须为整数，收到 {args.seed!r}")
        return 2  # pragma: no cover —— parser.error 不返回

    if args.preset == "formal":
        # formal 不用 --per-type：规模是 :data:`FORMAL_SIZES` 定死的 330 条，
        # 给个 per_type 只会让人以为它能改条数。仍照常校验以免非法值静默通过。
        try:
            _validate_args(args.per_type, args.seed)
        except ValueError as exc:
            parser.error(str(exc))
            return 2  # pragma: no cover
        tasks = build_formal_dataset(seed=args.seed)
        paths = write_formal_dataset(tasks, args.output_dir)
        _formal_summary(tasks, args.seed, args.output_dir)
        print("wrote " + " ".join(f"{k}={v}" for k, v in paths.items()))
        return 0

    try:
        _validate_args(args.per_type, args.seed)
    except ValueError as exc:
        parser.error(str(exc))
        return 2  # pragma: no cover —— parser.error 不返回

    tasks = build_qa_dataset(per_type=args.per_type, seed=args.seed)
    path = write_qa_dataset(tasks, args.output_dir)

    print(f"per_type={args.per_type} seed={args.seed} output={path}")
    # 表头标签用 ASCII：Windows 控制台代码页未必能正确渲染中文（同 build.py 的理由）。
    print(f"{'type':<14}{'train':>8}{'heldout':>10}{'total':>8}{'points':>9}")
    for task_type in TASK_TYPES:
        rows = [t for t in tasks if t.initial_data["任务类型"] == task_type]
        tr = sum(1 for t in rows if t.split is Split.TRAIN)
        ho = sum(1 for t in rows if t.split is Split.HELDOUT)
        pts = sum(len(t.rubric or ()) for t in rows)
        print(f"{TYPE_LABELS[task_type]:<14}{tr:>8}{ho:>10}{len(rows):>8}{pts:>9}")
    print(f"{'TOTAL':<14}"
          f"{sum(1 for t in tasks if t.split is Split.TRAIN):>8}"
          f"{sum(1 for t in tasks if t.split is Split.HELDOUT):>10}"
          f"{len(tasks):>8}"
          f"{sum(len(t.rubric or ()) for t in tasks):>9}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
