# --------------------------------------------------------------------------------------
# 场景模板 + 要点参数化（TASK-013）
#
# 16 条手写场景能撑住试标，撑不住 330 条正式校准 —— 「每条都手写 rubric」不可持续。
# 做法：把一条场景抽成**模板**（知识库 + 句法骨架），可变部分抽成槽位，
# 再用槽位组合表把它展开成 N 条任务。**rubric 文案与文档正文都从槽位生成**，
# 不是手写 —— 这是「参数化」与「复制粘贴换数字」的分界线。
#
# **为什么槽位必须同时进文档和 rubric**：只换问题不换文档，同知识库的十几条任务
# 会拿着**字节相同**的证据问不同问题，标注时看着像十几道题、判分时其实是同一道；
# 只换文档不换 rubric，更糟 —— rubric 会引用一个不存在的数值。两者同槽才能自洽。
#
# **模板边界与 ``Scenario`` 池的关系**：``Scenario`` 是**试标**路径（:func:`build_qa_dataset`
# 按 seed 抽 N 条、校准循环用）；``Template`` 是**正式**路径（:func:`build_formal_dataset`
# 一次铺满 330 条三 split）。两者共享同一批手写知识库正文，但**互不替代**：
# ``calibrate.py`` 只认 ``SCENARIOS``/``build_qa_dataset``，本单不碰它。
# --------------------------------------------------------------------------------------


@dataclass(frozen=True)
class Template:
    """一条场景模板 = 知识库句法骨架 + 槽位组合表。

    :param base_id: 知识库标识（``kb-d1`` / ``kb-g2`` …）。**它同时是防泄漏分组的键** ——
        同一 ``base_id`` 的所有变体必须落在同一 split，否则开发期见过答案的模板
        会在盲测期原样再考一次，分数虚高。契约里的「同一模板/知识库的变体不跨 split」
        就是按这个字段分组。
    :param slots: 槽位组合表。每行一组取值，一行 = 一条任务。**组合互不重复**
        （同一组槽位值不许出现两次），否则两条任务的文档与 rubric 会逐字节相同。
    :param docs: 知识库文档模板。正文里的槽位用 ``{槽位名}`` 占位，
        与 ``slots`` 的键一一对应。
    :param question: 问题模板。
    :param example_answer: 参考答案模板。
    :param points: rubric 要点模板，每个是 :func:`_pt` 产出的 dict，字段里可含 ``{槽位名}``。
    """

    base_id: str
    task_type: str
    docs: tuple[dict[str, str], ...]
    slots: tuple[dict[str, str], ...]
    question: str
    example_answer: str
    points: tuple[dict[str, Any], ...]

    @property
    def expanded_count(self) -> int:
        """这个模板能展开多少条任务 —— 等于槽位组合数。"""
        return len(self.slots)


def _pt(requirement: str, weight: float, evidence: list[str], partial: str,
        alts: list[str] | None = None, critical: bool = False) -> dict[str, Any]:
    """模板版评分点。与 :func:`_p` 同结构，唯一区别是**字段里可含 ``{槽位名}`` 占位**。

    字段里**绝不能出现字面花括号**（JSON、正则都爱用）—— 展开走的是 ``str.format``，
    遇到落单的 ``{`` 会抛 ``KeyError``/``IndexError``。生成期炸掉比产出错文档强。
    """
    return _p(requirement, weight, evidence, partial, alts, critical)


def _tmpl(base_id: str, task_type: str, docs: tuple[dict[str, str], ...],
          slots: tuple[dict[str, str], ...], question: str, example_answer: str,
          points: tuple[dict[str, Any], ...]) -> Template:
    """构造模板并**立刻自检**槽位闭合 —— 生成期就该炸，不该留到产物里才发现。

    查三件事：① 正文/问题/答案/rubric 里引用的槽位都在 ``slots`` 里声明了（漏声明 ⇒ KeyError）；
    ② ``slots`` 里声明的槽位都被正文至少用到一处（多声明 ⇒ 组合表膨胀但内容不变，
    同参数组合会出现两条逐字节相同的任务）；③ 槽位组合本身不重复。
    """
    used: set[str] = set()
    for text in [d["title"] for d in docs] + [d["text"] for d in docs] + [question, example_answer]:
        used |= _slot_names(text)
    for point in points:
        for field in ("requirement", "partial_rule"):
            used |= _slot_names(str(point[field]))
        used |= _slot_names("".join(point["accepted_alternatives"]))

    declared = set().union(*(set(s) for s in slots)) if slots else set()
    nested = sorted(f"{k}={v!r}" for s in slots for k, v in s.items() if _slot_names(v))
    if nested:
        # 槽位**值**不再参与展开（``_expand`` 只 format 正文文本），值里的占位会原样漏进产物
        raise ValueError(f"{base_id} 的槽位值里又写了占位：{nested[:2]}；值不二次展开，写死字面量")
    if declared != used:
        raise ValueError(
            f"{base_id} 槽位不闭合：正文用到 {sorted(used)}，slots 只声明了 {sorted(declared)}；"
            f"漏声明会 KeyError，多声明会让同一组参数生成重复任务"
        )

    keys = sorted(declared)
    signatures = [tuple(sorted(s.items())) for s in slots]
    if len(set(signatures)) != len(signatures):
        raise ValueError(f"{base_id} 的槽位组合有重复 —— 同参数会展开出两条逐字节相同的任务")
    return Template(base_id, task_type, docs, slots, question, example_answer, points)


#: 槽位占位 ``{名字}``。**不用 ``string.Formatter`` 解析**：它会把 JSON 里的 ``{``、
#: 正则量词 ``{2}`` 也当占位，报错信息还指向一个根本不存在的槽位。
_SLOT_RE = re.compile(r"\{([^{}]+)\}")


def _slot_names(text: str) -> set[str]:
    """抽出文本里用到的槽位名。"""
    return set(_SLOT_RE.findall(text))


def _cross(*groups: tuple[dict[str, str], ...]) -> tuple[dict[str, str], ...]:
    """槽位维度做笛卡尔积。

    330 条任务的槽位组合表手写不现实（每行还要重打一遍所有槽位的值），
    按维度写「3 行 + 5 行」远比手写 15 行省事，也更难写重。

    **允许后面的维度覆盖前面的同名槽位**（这正是省事的地方：只把要变的那个键
    再写一遍，不必把整个维度重打）。但仍要拦住一件事：**笛卡尔积里出现两行完全
    相同的组合** —— 那会让两条任务的文档与 rubric 逐字节一致，判分时是同一道题。
    """
    rows: list[dict[str, str]] = [{}]
    for group in groups:
        rows = [{**base, **slot} for base in rows for slot in group]
    signatures = [tuple(sorted(r.items())) for r in rows]
    if len(set(signatures)) != len(signatures):
        dupes = sorted({str(r) for r in signatures if signatures.count(r) > 1})
        raise ValueError(f"槽位维度交叉后有重复组合（会生成逐字节相同的两条任务）: {dupes[:2]}")
    return tuple(rows)


def _expand(template: Template, slots: Mapping[str, str]) -> Scenario:
    """把一个模板按一组槽位值展开成一条 :class:`Scenario`（供正式路径复用既有装配逻辑）。"""
    def fill(text: str) -> str:
        return text.format(**slots)

    docs = tuple({**d, "title": fill(d["title"]), "text": fill(d["text"])}
                 for d in template.docs)
    points = tuple(
        {**p,
         "requirement": fill(p["requirement"]),
         "partial_rule": fill(p["partial_rule"]),
         "accepted_alternatives": [fill(a) for a in p["accepted_alternatives"]],
         "evidence_ids": [fill(e) for e in p["evidence_ids"]]}
        for p in template.points
    )
    return Scenario(template.task_type, docs, fill(template.question),
                    fill(template.example_answer), points)


