def _doc(doc_id: str, title: str, text: str) -> dict[str, str]:
    return {"doc_id": doc_id, "title": title, "text": text}


def _p(requirement: str, weight: float, evidence: list[str], partial: str,
       alts: list[str] | None = None, critical: bool = False) -> dict[str, Any]:
    """一个评分点（``criterion_id`` 由 :func:`_materialize` 按位置补上，不在这里手写）。"""
    return {
        "requirement": requirement,
        "weight": weight,
        "evidence_ids": evidence,
        "partial_rule": partial,
        "accepted_alternatives": alts or [],
        "critical": critical,
    }


@dataclass(frozen=True)
class Scenario:
    """一条场景模板：知识库 + 问题 + 参考答案示例 + rubric 要点。

    同类型的场景构成一个池子，按 seed 打乱后取前 N 条 —— 所以 ``--per-type N`` 大于池子
    大小时会循环复用（``take`` 语义：只要 ``N > 0`` 就保证不越界）。
    """

    task_type: str
    docs: tuple[dict[str, str], ...]
    instruction: str
    example_answer: str
    points: tuple[dict[str, Any], ...]


