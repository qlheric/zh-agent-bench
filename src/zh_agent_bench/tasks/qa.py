"""B 场景任务构造器 —— 知识检索 QA（rubric 评分点 + 中文 judge）。

A 场景（``tasks/build.py``）给结构化表、算确定值、用四个比较算子判分。B 场景反过来：
**问题在中文文档里，答案主观开放**，判不了字符串相等 —— 于是改走 rubric：

    G = Σ wᵢ·sᵢ / Σ wᵢ ，  sᵢ ∈ {0, 0.5, 1}

逐条 rubric 打点、**程序聚合**（gpt-6-astra 头脑风暴 P0-1）。judge 只负责「这一条答没答到」
的二元/三值判断，加权求和是程序干的 —— 这样分数可复现、可回溯到具体哪条要点丢分。

**参考答案只是示例，不是评分依据。** ``ground_truth["example_answer"]`` 是「一个合格的
答案长什么样」给人看的，judge **不得**拿它做语义等价比对：那种做法会误杀合法答案，
也会奖励复述参考答案的人（P0-1 的原话）。

四种任务类型（撑起 Agent 卖点，最后两类是 A 场景考不到的）：

| 类型 | 考点 | 正确行为 |
|---|---|---|
| ``单跳`` | 一次检索能答 | 引用那一篇，给出事实 |
| ``多跳`` | 跨 >=2 篇文档 | 把两篇的信息接起来 |
| ``证据不足`` | 库里缺关键事实 | **指出缺口**，不编造 |
| ``不可回答`` | 问题本身信息不足 | **要澄清**，不硬答 |

后两类是 rubric 的真正试金石：没有 rubric、只比参考答案的话，这两种「不回答」会被
判成「没答上来」——而它们恰恰是正确行为。

**确定性铁律**（与 ``build.py`` 同款）：同 seed 两次产物逐字节一致；无随机源泄漏、
无时间戳、无 ``set``/``dict`` 迭代序依赖（排序全序给 tiebreak）。**运行时仅 stdlib**。
"""

