def _materialize(scenario: Scenario, task_id: str) -> tuple[dict[str, Any], ...]:
    """给场景的评分点补上 ``criterion_id``（按位置），其余字段原样透传。"""
    return tuple(
        {"criterion_id": f"{task_id}-c{i}", **{k: point[k] for k in RUBRIC_FIELDS if k != "criterion_id"}}
        for i, point in enumerate(scenario.points, start=1)
    )


def build_task(task_id: str, scenario: Scenario, split: Split) -> Task:
    """把一个场景实例化成一条 :class:`Task`（并就地校验 rubric）。"""
    rubric = _materialize(scenario, task_id)
    docs = [dict(d) for d in scenario.docs]
    validate_rubric(rubric, {d["doc_id"] for d in docs})
    return Task(
        id=task_id,
        category=Category.RETRIEVAL,
        schema_version=SCHEMA_VERSION,
        instruction=scenario.instruction,
        initial_data={"任务类型": scenario.task_type, "knowledge": docs},
        tool_names=(QA_TOOL_NAME,),
        # ``example_answer`` 是**示例**不是判分依据（P0-1）：judge 逐条打 rubric，
        # 不拿它做语义等价比对，所以键名就叫 example_answer，key 一眼能看出定位。
        ground_truth={"example_answer": scenario.example_answer},
        answer_spec=AnswerSpec(
            kind=AnswerKind.STRING,
            comparison=QA_COMPARISON,
            normalization=Normalization.NONE,
        ),
        split=split,
        rubric=rubric,
    )


def _split_of(n: int, index: int, h_count: int) -> Split:
    """id 升序后前 ``h_count`` 条进 heldout，其余进 train（与 A 场景同规则）。"""
    return Split.HELDOUT if index < h_count else Split.TRAIN


def _pick(pool: Sequence[Scenario], rng: random.Random, index: int) -> Scenario:
    """按 seed 打乱后取第 ``index`` 条；``index`` 超过池长时循环取（与 build.take 同语义）。"""
    items = list(pool)
    rng.shuffle(items)
    return items[index % len(items)]


def build_qa_dataset(per_type: int = 2, seed: int = 42) -> list[Task]:
    """生成 B 场景任务。返回按 id 升序的稳定列表。

    ``per_type`` 是**每个类型**的条数；总条数 = ``per_type * 4``。

    ``per_type`` 大于池子容量时**报错**而不是循环复用：复用会让同一场景被 judge
    判两遍、一致率被同一条样本计两次，数字直接失真（与 ``calibrate.max_per_type``
    拒绝超额是同一条理由）。
    """
    capacity = min(len(pool) for pool in SCENARIOS.values())
    if per_type > capacity:
        raise ValueError(
            f"--per-type {per_type} 超过场景池容量 {capacity}（每类 {len(SCENARIOS['单跳'])} 条），"
            f"再大就得循环复用同一批场景，同一条样本会被计两次"
        )

    tasks: list[Task] = []
    seq = 0
    for task_type in TASK_TYPES:
        pool = SCENARIOS[task_type]
        h_count = heldout_count(per_type)
        for index in range(per_type):
            # 随机源按 (seed, 类型, 下标) 独立开：往池里加场景或改 per_type 都不会
            # 打乱其它类型已有的内容，扩容是纯追加而非全量重排。
            rng = random.Random(f"{seed}:qa:{task_type}:{index}")
            scenario = _pick(pool, rng, index)
            seq += 1
            tasks.append(build_task(f"qa-{seq:04d}", scenario, _split_of(per_type, index, h_count)))
    tasks.sort(key=lambda t: t.id)
    return tasks


