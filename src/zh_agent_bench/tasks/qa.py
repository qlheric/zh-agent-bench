# 正式规模：330 条三 split（trial / dev / blind）
#
# 与试标路径的差别有两条，都是「正式校准」逼出来的：
#
# 1）**按模板分组，不按行随机切**。同一 ``base_id`` 的十几条变体共用一份知识库，
#    随机切分必然有两条同源任务分到 dev 与 blind —— 开发期标注员见过的答案原样
#    再考一次，盲测分数虚高。分组切分让 ``base_id`` 整体归属某一个 split。
# 2）**三级 split 写进 initial_data**，而 schema 的 ``Split`` 枚举只有 train/heldout
#    两值（那是 A 场景的判据，改它就越界）。B 场景要的是「试标 60 / 开发 120 /
#    盲测 150」三档，多出来的那一维只能挂在 ``initial_data`` 上。
# --------------------------------------------------------------------------------------

#: 三级 split 的名字，顺序即切分优先级。
B_SPLITS = ("trial", "dev", "blind")

#: 老板拍板的正式规模：试标 60 / 开发 120 / 盲测 150 = 330。
FORMAL_SIZES: dict[str, int] = {"trial": 60, "dev": 120, "blind": 150}

#: ``base_id`` → 归属的 split。
#:
#: 逐个知识库写死，不做算法切分：知识库只有 24 个，每类 6 个，切分方案**肉眼可审**
#: 比自动贪心可解释得多 —— 「盲测为什么用这几个库」在评审里要能当场答上来。
#:
#: 容量：每类 6 个模板、每模板 15 行（每类池 90 条），trial 恰好用 1 个模板装满，
#: dev 用 2 个，blind 用 2~3 个再截到配额。
TEMPLATE_SPLIT: dict[str, str] = {
    # 单跳
    "kb-d1": "trial", "kb-d2": "blind", "kb-d3": "dev",
    "kb-d4": "dev", "kb-d5": "blind", "kb-d6": "blind",
    # 多跳
    "kb-m1": "trial", "kb-m2": "dev", "kb-m3": "dev",
    "kb-m4": "blind", "kb-m5": "blind", "kb-m6": "blind",
    # 证据不足
    "kb-g1": "trial", "kb-g2": "dev", "kb-g3": "dev",
    "kb-g4": "blind", "kb-g5": "blind", "kb-g6": "blind",
    # 不可回答
    "kb-c1": "trial", "kb-c2": "dev", "kb-c3": "dev",
    "kb-c4": "blind", "kb-c5": "blind", "kb-c6": "blind",
}


@dataclass(frozen=True)
class FormalTask:
    """正式集的一条任务。``split`` 是三级 split 名字（不是 schema 的两值枚举）。"""

    task: Task
    split: str
    base_id: str

    @property
    def task_type(self) -> str:
        return str(self.task.initial_data["任务类型"])


#: 每档每个任务类型要的条数。
#:
#: **为什么 blind 不是 150÷4 = 37**：37×4 = 148，不够 150；38×4 = 152，多出 2 条。
#: 取整除得 37、剩下 2 条按类型顺序补给 blind 的前两个类型（不可回答、多跳）。
#: 写死在这里而不是 ``size // 4``，是因为「多出来的 2 条给谁」是**编排决定**，
#: 让代码自动摊平就等于把这个决定藏进了取模里。
FORMAL_PER_TYPE: dict[str, dict[str, int]] = {
    "trial": {tt: FORMAL_SIZES["trial"] // len(TASK_TYPES) for tt in TASK_TYPES},
    "dev": {tt: FORMAL_SIZES["dev"] // len(TASK_TYPES) for tt in TASK_TYPES},
    "blind": {
        "单跳": 37,
        "多跳": 38,
        "证据不足": 37,
        "不可回答": 38,
    },
}


def _assign_splits() -> dict[str, list[Template]]:
    """切分表的自检 + 配额内选模板。漏登记或多登记都在生成期炸，不留到产物里才发现。"""
    known = {t.base_id for pool in TEMPLATES.values() for t in pool}
    unknown = sorted(set(TEMPLATE_SPLIT) - known)
    if unknown:
        raise ValueError(f"TEMPLATE_SPLIT 里登记了不存在的 base_id: {unknown}")
    missing = sorted(known - set(TEMPLATE_SPLIT))
    if missing:
        raise ValueError(f"这些 base_id 没登记 split（会漏掉整批任务）: {missing}")
    for task_type, pool in TEMPLATES.items():
        for split in B_SPLITS:
            cap = sum(t.expanded_count for t in pool if TEMPLATE_SPLIT[t.base_id] == split)
            want = FORMAL_PER_TYPE[split][task_type]
            if cap < want:
                raise ValueError(
                    f"{task_type}/{split} 容量 {cap} < 需要的 {want} —— "
                    f"调 TEMPLATE_SPLIT 或加模板/加槽位组合"
                )
    return _plan_splits()


def _plan_splits() -> dict[str, dict[str, list[tuple[Template, int]]]]:
    """每档每类选模板并算好「取前几条」，多出来的不生成。

    **为什么必须截断**：模板池比正式规模多（360 vs 330）。多出来的槽位组合不是
    「备而不用」的富余，而是**同一份知识库的近似重复**——全装进去等于同一档里
    塞进 37 条同源任务，正是判据 ⑦ 要治的病。池子留宽是为了将来加 split 有余地，
    不是为了超发。截断取**按槽位表顺序的前 N 条**，规则简单到回放器一眼能复算。
    """
    plan: dict[str, dict[str, list[tuple[Template, int]]]] = {}
    for split in B_SPLITS:
        per_type: dict[str, list[tuple[Template, int]]] = {}
        for task_type in TASK_TYPES:
            need = FORMAL_PER_TYPE[split][task_type]
            mine = [t for t in TEMPLATES[task_type] if TEMPLATE_SPLIT[t.base_id] == split]
            capacity = sum(t.expanded_count for t in mine)
            if capacity < need:
                raise ValueError(
                    f"{task_type}/{split} 容量 {capacity} < 需要的 {need} —— "
                    f"调 TEMPLATE_SPLIT 或加模板/加槽位组合"
                )
            picked: list[tuple[Template, int]] = []
            left = need
            for template in mine:
                if left <= 0:
                    break
                take = min(template.expanded_count, left)
                picked.append((template, take))
                left -= take
            per_type[task_type] = picked
        plan[split] = per_type
    return plan


_SPLIT_PLAN: dict[str, dict[str, list[tuple[Template, int]]]] = _assign_splits()


def build_formal_dataset(seed: int = 42) -> list[FormalTask]:
    """生成 330 条正式任务，按 ``trial / dev / blind`` 三档打散（确定性打散）。

    **按行随机打散**是刻意的：``TEMPLATE_SPLIT`` 已经保证同一知识库不跨 split，
    剩下的自由度是「同 split 内任务 id 的分配顺序」。打散让任务 id 不按知识库连号，
    标注员连着标十条不会发现「这十条是同一个模板换的数」，从而把「模板级」的
    一致性偏差混进分数里。

    :param seed: 只决定 split 内的排列，**不决定任何任务内容** —— 内容全部由
        模板与槽位组合表定死。换个 seed 得到的是同一批 330 条任务、不同的 id 顺序。
    """
    rng = random.Random(f"{seed}:qa-formal")
    tasks: list[FormalTask] = []
    for split in B_SPLITS:
        rows: list[FormalTask] = []
        for task_type in TASK_TYPES:
            for template, take in _SPLIT_PLAN[split][task_type]:
                for index, slots in enumerate(template.slots[:take], start=1):
                    task = build_task(
                        f"qa-{split}-{template.base_id}-{index:02d}",
                        _expand(template, slots),
                        Split.TRAIN,
                    )
                    rows.append(FormalTask(task, split, template.base_id))
        rng.shuffle(rows)
        tasks.extend(rows)
    return tasks


def write_formal_dataset(tasks: Sequence[FormalTask], output_dir: Path) -> dict[str, Path]:
    """写成 ``<output_dir>/{trial,dev,blind}/qa.jsonl`` 三个目录。原子写。

    每个 split 一个文件（而不是一个带 split 字段的大文件）：盲测集要能整目录
    封存、不给开发流程读，单文件做不到那个「不打开」的保证。
    """
    output_dir.mkdir(parents=True, exist_ok=True)
    paths: dict[str, Path] = {}
    for split in B_SPLITS:
        rows = [ft.task for ft in tasks if ft.split == split]
        target = output_dir / split / QA_FILENAME
        target.parent.mkdir(parents=True, exist_ok=True)
        payload = "".join(_dump_line(t) for t in sorted(rows, key=lambda t: t.id))
        tmp = target.with_suffix(target.suffix + ".tmp")
        tmp.write_text(payload, encoding="utf-8", newline="\n")
        os.replace(tmp, target)
        paths[split] = target
    return paths


