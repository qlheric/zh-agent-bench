#: 二值点的标记：写「→ 0」表示**本点不存在半分情形**（三值点写「… → 0.5」）。
#:
#: 必须用正则而不能用 ``"→ 0" in rule`` —— 它是 ``"→ 0.5"`` 的**子串**，
#: 于是每一个三值点都会被误判成二值（写 partial_rule 时踩到的：生成器直接抛
#: 「partial_rule 必须写明 0.5 的触发情形」）。``(?![.\d])`` 把 ``0.5`` / ``0.50`` 排除掉，
#: 但 ``0`` / ``0.0`` 这两种「零」的写法都收。
_BINARY_MARK = re.compile(r"→\s*0(?:\.0+)?(?![.\d])")


def partial_rule_kind(rule: str) -> str:
    """:func:`validate_rubric` 与测试共用的规则分类。

    :returns: ``"ternary"``（写了 0.5 触发情形）、``"binary"``（显式宣告半分不存在）、
        或 ``"undecidable"``（两种都没写 —— 这才是真不可判，必须拒收）。
    """
    if "0.5" in rule:
        return "ternary"
    return "binary" if _BINARY_MARK.search(rule) else "undecidable"


def validate_rubric(rubric: Sequence[dict[str, Any]], doc_ids: set[str]) -> None:
    """结构校验。不通过就抛 ``ValueError`` —— 生成期就该炸，不该留到判分时才发现。

    挡的是四类「rubric 不可判分」：字段缺失、权重不归一、分值不可判、
    ``evidence_ids`` 指向不存在的文档（judge 核证据时找不到出处，这一条就废了）。
    """
    if not MIN_POINTS <= len(rubric) <= MAX_POINTS:
        raise ValueError(f"评分点须 {MIN_POINTS}–{MAX_POINTS} 个，实际 {len(rubric)}")

    seen_ids: set[str] = set()
    for i, point in enumerate(rubric, start=1):
        missing = [f for f in RUBRIC_FIELDS if f not in point]
        if missing:
            raise ValueError(f"第 {i} 个评分点缺字段: {missing}")
        extra = sorted(set(point) - set(RUBRIC_FIELDS))
        if extra:
            raise ValueError(f"第 {i} 个评分点有多余字段: {extra}")

        cid = point["criterion_id"]
        if cid in seen_ids:
            raise ValueError(f"criterion_id 重复: {cid}")
        seen_ids.add(cid)

        if not isinstance(point["requirement"], str) or not point["requirement"].strip():
            raise ValueError(f"{cid}: requirement 必须是非空字符串")
        if not isinstance(point["weight"], float) or not 0 < point["weight"] <= 1:
            raise ValueError(f"{cid}: weight 必须是 (0, 1] 的 float")
        if not isinstance(point["critical"], bool):
            raise ValueError(f"{cid}: critical 必须是 bool")

        ev = point["evidence_ids"]
        if not isinstance(ev, list) or not all(isinstance(x, str) for x in ev):
            raise ValueError(f"{cid}: evidence_ids 必须是字符串列表")
        unknown = [x for x in ev if x not in doc_ids]
        if unknown:
            raise ValueError(f"{cid}: evidence_ids 指向不存在的文档: {unknown}")

        if not isinstance(point["accepted_alternatives"], list):
            raise ValueError(f"{cid}: accepted_alternatives 必须是列表")

        # 分值可判：点要么是「三值」——写明什么情况给 0.5；要么是「二值」——明确宣告
        # 半分情形不存在（``→ 0``）。两种都必须**写出来**：judge 拿到一句含糊的
        # partial_rule（「部分满足可给半分」而没说什么算部分满足）时，两个标注员会各打各的，
        # 校准的分歧就从这条漏出去。程序能机械验的只有「分值规则有没有落在白名单里」，
        # 规则措辞本身的可判性得由人写、被人读。
        partial = point["partial_rule"]
        if not isinstance(partial, str) or not partial.strip():
            raise ValueError(f"{cid}: partial_rule 必须是非空字符串")
        if partial_rule_kind(partial) == "undecidable":
            raise ValueError(
                f"{cid}: partial_rule 必须写明 0.5 的触发情形，或显式宣告本点为二值（→ 0）"
            )

    total = sum(p["weight"] for p in rubric)
    if abs(total - 1.0) > 1e-9:
        # 权重归一 ⇒ G 直接读作百分比，跨任务的分数才可比。
        raise ValueError(f"权重之和应为 1.0，实际 {total!r}")


def aggregate_rubric(rubric: Sequence[dict[str, Any]], scores: dict[str, float]) -> tuple[float, bool]:
    """把逐点评分聚合成总分。``scores`` 键是 ``criterion_id``，值须 ∈ {0, 0.5, 1}。

    :returns: ``(G, capped)``。``G = Σ wᵢ·sᵢ / Σ wᵢ``；只要有一个 ``critical`` 点得 0，
        ``G`` 就被封顶到 :data:`CRITICAL_CAP`（关键错误不可被其他正确句抵消）。
        ``capped`` 告诉调用方分数是否被封过 —— 校准分析要区分「答不全」与「关键点错」。
    """
    if set(scores) != {p["criterion_id"] for p in rubric}:
        raise ValueError("scores 的键必须与 rubric 的 criterion_id 完全一致")

    total_weight = 0.0
    acc = 0.0
    capped = False
    for point in rubric:
        s = scores[point["criterion_id"]]
        if s not in ALLOWED_SCORES:
            raise ValueError(f"{point['criterion_id']} 的得分 {s!r} 不在 {ALLOWED_SCORES} 内")
        w = point["weight"]
        acc += w * s
        total_weight += w
        if point["critical"] and s == 0.0:
            capped = True
    g = acc / total_weight
    if capped and g > CRITICAL_CAP:
        g = CRITICAL_CAP
    return g, capped


